-- ============================================================================
-- V1__init_schemas_roles_and_tables.sql
-- Strictly immutable once applied. Defines `portfolio` and `analytics` schemas,
-- all 12 core tables, B-Tree foreign key indexes, GIN full-text index, and
-- three-tier least-privilege role grants.
-- ============================================================================

CREATE SCHEMA IF NOT EXISTS portfolio;
CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE portfolio.documents (
    id UUID PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('RESUME', 'PAPER', 'SLIDES', 'IMAGE', 'ATTACHMENT')),
    original_filename TEXT NOT NULL,
    mime_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL CHECK (size_bytes >= 0),
    sha256 TEXT NOT NULL CHECK (char_length(sha256) = 64),
    storage_key TEXT NOT NULL UNIQUE,
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE portfolio.profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONSTRAINT chk_profile_singleton CHECK (id = 1),
    full_name TEXT NOT NULL,
    headline TEXT NOT NULL,
    bio_markdown TEXT NOT NULL,
    location TEXT NULL,
    availability TEXT NULL,
    social_links JSONB NOT NULL DEFAULT '[]'::jsonb,
    resume_document_id UUID NULL REFERENCES portfolio.documents(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_profile_resume_document_id
    ON portfolio.profile (resume_document_id)
    WHERE resume_document_id IS NOT NULL;

CREATE TABLE portfolio.experiences (
    id UUID PRIMARY KEY,
    company TEXT NOT NULL,
    title TEXT NOT NULL,
    location TEXT NULL,
    start_date DATE NOT NULL,
    end_date DATE NULL,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    highlights JSONB NOT NULL DEFAULT '[]'::jsonb,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_experiences_sort_order
    ON portfolio.experiences (sort_order ASC, start_date DESC);

CREATE TABLE portfolio.education (
    id UUID PRIMARY KEY,
    institution TEXT NOT NULL,
    degree TEXT NOT NULL,
    field_of_study TEXT NULL,
    start_date DATE NOT NULL,
    end_date DATE NULL,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_education_sort_order
    ON portfolio.education (sort_order ASC, start_date DESC);

CREATE TABLE portfolio.certifications (
    id UUID PRIMARY KEY,
    name TEXT NOT NULL,
    issuer TEXT NOT NULL,
    issued_date DATE NOT NULL,
    expires_date DATE NULL,
    credential_url TEXT NULL,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_certifications_sort_order
    ON portfolio.certifications (sort_order ASC, issued_date DESC);

CREATE TABLE portfolio.skills (
    id UUID PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    category TEXT NOT NULL,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INT NOT NULL DEFAULT 0
);

CREATE INDEX idx_skills_featured_sort
    ON portfolio.skills (is_featured, sort_order ASC, name ASC);

CREATE TABLE portfolio.experience_skills (
    experience_id UUID NOT NULL REFERENCES portfolio.experiences(id) ON DELETE CASCADE,
    skill_id UUID NOT NULL REFERENCES portfolio.skills(id) ON DELETE CASCADE,
    PRIMARY KEY (experience_id, skill_id)
);

CREATE INDEX idx_experience_skills_experience_id
    ON portfolio.experience_skills (experience_id);

CREATE INDEX idx_experience_skills_skill_id
    ON portfolio.experience_skills (skill_id);

CREATE TABLE portfolio.projects (
    id UUID PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    summary TEXT NOT NULL,
    case_study_markdown TEXT NOT NULL,
    repo_url TEXT NULL,
    live_url TEXT NULL,
    cover_document_id UUID NULL REFERENCES portfolio.documents(id) ON DELETE SET NULL,
    status TEXT NOT NULL CHECK (status IN ('ACTIVE', 'ARCHIVED', 'PROTOTYPE')),
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_projects_cover_document_id
    ON portfolio.projects (cover_document_id)
    WHERE cover_document_id IS NOT NULL;

CREATE INDEX idx_projects_featured_sort
    ON portfolio.projects (is_featured DESC, sort_order ASC, updated_at DESC);

CREATE TABLE portfolio.project_skills (
    project_id UUID NOT NULL REFERENCES portfolio.projects(id) ON DELETE CASCADE,
    skill_id UUID NOT NULL REFERENCES portfolio.skills(id) ON DELETE CASCADE,
    PRIMARY KEY (project_id, skill_id)
);

CREATE INDEX idx_project_skills_project_id
    ON portfolio.project_skills (project_id);

CREATE INDEX idx_project_skills_skill_id
    ON portfolio.project_skills (skill_id);

CREATE TABLE portfolio.writeups (
    id UUID PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    title TEXT NOT NULL,
    subtitle TEXT NULL,
    summary TEXT NOT NULL,
    body_markdown TEXT NOT NULL,
    tags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    status TEXT NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    reading_time_min INT NOT NULL DEFAULT 1 CHECK (reading_time_min >= 1),
    cover_document_id UUID NULL REFERENCES portfolio.documents(id) ON DELETE SET NULL,
    search_vector TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('english', coalesce(title, '')), 'A')
        || setweight(to_tsvector('english', coalesce(subtitle, '') || ' ' || coalesce(summary, '')), 'B')
        || setweight(to_tsvector('english', coalesce(body_markdown, '')), 'C')
    ) STORED,
    published_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_writeups_cover_document_id
    ON portfolio.writeups (cover_document_id)
    WHERE cover_document_id IS NOT NULL;

CREATE INDEX idx_writeups_status_published
    ON portfolio.writeups (status, published_at DESC NULLS LAST, updated_at DESC);

CREATE INDEX idx_writeups_tags_gin
    ON portfolio.writeups USING GIN (tags);

CREATE INDEX idx_writeups_search_vector_gin
    ON portfolio.writeups USING GIN (search_vector);

CREATE TABLE analytics.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL CHECK (event_type IN ('PAGE_VIEW', 'WRITEUP_READ', 'PROJECT_CLICK', 'DOCUMENT_DOWNLOAD')),
    path TEXT NOT NULL,
    entity_id UUID NULL,
    referrer_host TEXT NULL,
    platform TEXT NOT NULL CHECK (platform IN ('WEB', 'ANDROID', 'IOS', 'DESKTOP')),
    viewport_tier TEXT NOT NULL CHECK (viewport_tier IN ('COMPACT', 'MEDIUM', 'EXPANDED', 'LARGE', 'EXTRA_LARGE')),
    visitor_hash TEXT NOT NULL CHECK (char_length(visitor_hash) = 64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_analytics_events_created_at
    ON analytics.events (created_at DESC);

CREATE INDEX idx_analytics_events_type_path
    ON analytics.events (event_type, path, created_at DESC);

CREATE INDEX idx_analytics_events_entity_id
    ON analytics.events (entity_id)
    WHERE entity_id IS NOT NULL;

CREATE TABLE analytics.daily_rollups (
    day DATE NOT NULL,
    event_type TEXT NOT NULL CHECK (event_type IN ('PAGE_VIEW', 'WRITEUP_READ', 'PROJECT_CLICK', 'DOCUMENT_DOWNLOAD')),
    path TEXT NOT NULL,
    platform TEXT NOT NULL CHECK (platform IN ('WEB', 'ANDROID', 'IOS', 'DESKTOP')),
    viewport_tier TEXT NOT NULL CHECK (viewport_tier IN ('COMPACT', 'MEDIUM', 'EXPANDED', 'LARGE', 'EXTRA_LARGE')),
    event_count BIGINT NOT NULL DEFAULT 0 CHECK (event_count >= 0),
    unique_visitors BIGINT NOT NULL DEFAULT 0 CHECK (unique_visitors >= 0),
    PRIMARY KEY (day, event_type, path, platform, viewport_tier)
);

REVOKE ALL ON SCHEMA portfolio FROM PUBLIC;
REVOKE ALL ON SCHEMA analytics FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA portfolio FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA analytics FROM PUBLIC;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'portfolio_admin') THEN
        GRANT USAGE ON SCHEMA portfolio, analytics TO portfolio_admin;
        GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA portfolio TO portfolio_admin;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA portfolio TO portfolio_admin;
        GRANT SELECT ON analytics.events TO portfolio_admin;
        GRANT SELECT, INSERT, UPDATE, DELETE ON analytics.daily_rollups TO portfolio_admin;
        GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA analytics TO portfolio_admin;
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'portfolio_public') THEN
        GRANT USAGE ON SCHEMA portfolio, analytics TO portfolio_public;
        GRANT SELECT ON ALL TABLES IN SCHEMA portfolio TO portfolio_public;
        GRANT INSERT ON analytics.events TO portfolio_public;
        GRANT USAGE ON SEQUENCE analytics.events_id_seq TO portfolio_public;
    END IF;
END $$;
